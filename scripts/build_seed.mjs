#!/usr/bin/env node
/**
 * Build data/seed.sql from the exported JSON dataset.
 *
 * The tariff rows never ship to the browser: this file is imported into
 * Cloudflare D1, which is the only copy the Worker can read.
 *
 *   node scripts/build_seed.mjs
 *   npx wrangler d1 execute customs-calc --remote --file=data/seed.sql
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "data");

const rows = JSON.parse(readFileSync(join(dataDir, "hsn.json"), "utf8"));
const fta = JSON.parse(readFileSync(join(dataDir, "fta.json"), "utf8"));
const meta = JSON.parse(readFileSync(join(dataDir, "meta.json"), "utf8"));

if (!Array.isArray(rows) || rows.length !== meta.line_count) {
  throw new Error(`hsn.json has ${rows.length} rows, meta says ${meta.line_count}`);
}
if (!Array.isArray(fta.rates) || fta.rates.length !== rows.length) {
  throw new Error(`fta.json has ${fta.rates.length} rates for ${rows.length} rows`);
}
if (fta.columns.length !== meta.columns?.length) {
  throw new Error("fta.json columns do not match meta.json columns");
}

const sqlString = (value) => `'${String(value).replace(/'/g, "''")}'`;
const sqlNumber = (value) => {
  const n = Number(value);
  if (!Number.isFinite(n)) throw new Error(`Non-finite number: ${value}`);
  return String(n);
};
const sqlText = (value) =>
  sqlString(String(value ?? "").replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, " ").replace(/\r?\n/g, " "));

const columns = [
  "code",
  "description",
  "chapter",
  "bcd_statutory",
  "bcd_effective",
  "aidc",
  "sws",
  "igst",
  "cess",
  "flag",
  "fta",
];

const BATCH = 50;
const parts = [];

parts.push("-- Generated by scripts/build_seed.mjs. Do not edit by hand.");
parts.push(`-- Dataset ${meta.version} · ${meta.generated} · ${rows.length} tariff lines.`);
parts.push("");
parts.push("DROP TABLE IF EXISTS hsn_stage;");
parts.push(`CREATE TABLE hsn_stage (
  code           TEXT PRIMARY KEY,
  description    TEXT NOT NULL,
  chapter        INTEGER NOT NULL,
  bcd_statutory  REAL NOT NULL,
  bcd_effective  REAL NOT NULL,
  aidc           REAL NOT NULL,
  sws            REAL NOT NULL,
  igst           REAL NOT NULL,
  cess           REAL NOT NULL,
  flag           INTEGER NOT NULL,
  fta            TEXT NOT NULL
);`);
parts.push("");

for (let start = 0; start < rows.length; start += BATCH) {
  const batch = rows.slice(start, start + BATCH);
  const values = batch.map((row, offset) => {
    const index = start + offset;
    if (row.length < 10) throw new Error(`Row ${index} is malformed`);
    const ftaRates = fta.rates[index];
    if (!Array.isArray(ftaRates) || ftaRates.length !== fta.columns.length + 1) {
      throw new Error(`FTA row ${index} is not aligned`);
    }
    return `(${[
      sqlString(row[0]),
      sqlText(row[1]),
      sqlNumber(row[2]),
      sqlNumber(row[3]),
      sqlNumber(row[4]),
      sqlNumber(row[5]),
      sqlNumber(row[6]),
      sqlNumber(row[7]),
      sqlNumber(row[8]),
      sqlNumber(row[9]),
      sqlString(JSON.stringify(ftaRates)),
    ].join(", ")})`;
  });
  parts.push(
    `INSERT INTO hsn_stage (${columns.join(", ")}) VALUES\n  ${values.join(",\n  ")};`,
  );
}

parts.push("");
parts.push("DROP TABLE IF EXISTS hsn;");
parts.push("ALTER TABLE hsn_stage RENAME TO hsn;");
parts.push("CREATE INDEX IF NOT EXISTS idx_hsn_chapter ON hsn (chapter);");
parts.push("");

const settings = {
  meta: {
    ...meta,
    free_api_monthly_limit: 10,
    paid_monthly_limit: 1000000,
  },
};
parts.push("DELETE FROM settings;");
for (const [key, value] of Object.entries(settings)) {
  parts.push(
    `INSERT INTO settings (key, value) VALUES (${sqlString(key)}, ${sqlString(JSON.stringify(value))});`,
  );
}
parts.push("");

const out = join(dataDir, "seed.sql");
writeFileSync(out, parts.join("\n"), "utf8");
const size = (Buffer.byteLength(parts.join("\n")) / (1024 * 1024)).toFixed(1);
console.log(`Wrote ${out} (${rows.length} rows, ${size} MB)`);
